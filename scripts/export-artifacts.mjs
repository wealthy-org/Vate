#!/usr/bin/env node
// Turns the Foundry build output into the files the app and the deploy script consume:
//   src/config/testnet-fixture.json            addresses + hashes (small, bundled)
//   src/config/testnet-fixture.initcode.json   creation code (large, lazy-loaded / CLI only)
//   src/abi/testnet.generated.ts               typed ABIs of the test contracts
// Run `pnpm contracts:build` first. Addresses are deterministic (CREATE2 + CREATE nonces).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getContractAddress, keccak256, stringToHex } from 'viem';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (file, contract) =>
  JSON.parse(readFileSync(join(root, 'contracts/out', file, `${contract}.json`), 'utf8'));

// Canonical deterministic deployment proxy (Arachnid). Present on Robinhood Chain Testnet.
const CREATE2_FACTORY = '0x4e59b44847b379578588920cA78FbF26c0B4956C';
const SALT_LABEL = 'VATE testnet fixture v1';
const salt = keccak256(stringToHex(SALT_LABEL));

const deployment = out('VateTestnetDeployment.sol', 'VateTestnetDeployment');
const initCode = deployment.bytecode.object;
if (!/^0x[0-9a-f]+$/i.test(initCode) || initCode.includes('__$')) {
  throw new Error('Unexpected creation code (unlinked library placeholder or empty build).');
}

const deploymentAddress = getContractAddress({ opcode: 'CREATE2', from: CREATE2_FACTORY, salt, bytecode: initCode });
const child = (from, nonce) => getContractAddress({ opcode: 'CREATE', from, nonce: BigInt(nonce) });
// Contracts start at nonce 1 (EIP-161). The constructor creates the token first, then 4 vaults.
const usdg = child(deploymentAddress, 1);
const vaultKeys = ['I', 'II', 'III', 'IV'];
const vaults = vaultKeys.map((key, i) => {
  const address = child(deploymentAddress, 2 + i);
  return { key, address, marketAdapter: child(address, 1) };
});

const fixture = {
  version: 1,
  note: 'Generated by scripts/export-artifacts.mjs. Do not edit by hand.',
  chainId: 46630,
  create2Factory: CREATE2_FACTORY,
  saltLabel: SALT_LABEL,
  salt,
  initCodeHash: keccak256(initCode),
  initCodeBytes: (initCode.length - 2) / 2,
  compiler: { solc: '0.8.28', evmVersion: 'paris', optimizerRuns: 200, bytecodeHash: 'none' },
  deployment: deploymentAddress,
  usdg,
  vaults,
};
writeFileSync(join(root, 'src/config/testnet-fixture.json'), JSON.stringify(fixture, null, 2) + '\n');
writeFileSync(join(root, 'src/config/testnet-fixture.initcode.json'), JSON.stringify({ initCode }) + '\n');

const abiTs = [
  '// Generated by scripts/export-artifacts.mjs from contracts/out. Do not edit by hand.',
  '/* eslint-disable */',
  `export const TEST_USDG_ABI = ${JSON.stringify(out('TestUSDG.sol', 'TestUSDG').abi)} as const;`,
  `export const TEST_VAULT_ABI = ${JSON.stringify(out('TestVaultV2.sol', 'TestVaultV2').abi)} as const;`,
  `export const TEST_ADAPTER_ABI = ${JSON.stringify(out('TestMarketAdapter.sol', 'TestMarketAdapter').abi)} as const;`,
  `export const TEST_DEPLOYMENT_ABI = ${JSON.stringify(deployment.abi)} as const;`,
  '',
].join('\n');
writeFileSync(join(root, 'src/abi/testnet.generated.ts'), abiTs);

console.log(JSON.stringify({ ...fixture, note: undefined }, null, 2));
